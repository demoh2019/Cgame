"""Jolt XPBD soft-body tethers: settings, native wiring, and path models.

The LRA constraints are generated by Jolt for pinned cloth vertices.
Reference-model tests check Euclidean vs geodesic cloth distances and safe
range clamping. Native Jolt execution is checked separately in the CI job.
"""

from pathlib import Path
import heapq
import math
import random
import unittest


ROOT = Path(__file__).resolve().parents[2]
PROJECT_H = ROOT / "modules/jolt_physics/jolt_project_settings.h"
PROJECT_CPP = ROOT / "modules/jolt_physics/jolt_project_settings.cpp"
BODY_CPP = ROOT / "modules/jolt_physics/objects/jolt_soft_body_3d.cpp"
JOLT_H = ROOT / "thirdparty/jolt_physics/Jolt/Physics/SoftBody/SoftBodySharedSettings.h"
JOLT_CPP = ROOT / "thirdparty/jolt_physics/Jolt/Physics/SoftBody/SoftBodySharedSettings.cpp"
SCRIPT = ROOT / "tests/stress/physics_jolt_softbody_lra_regression.gd"


def euclidean(a, b):
    return math.dist(a, b)


def shortest_path(points, edges, source):
    adjacency = [[] for _ in points]
    for u, v in edges:
        w = euclidean(points[u], points[v])
        adjacency[u].append((v, w))
        adjacency[v].append((u, w))
    lengths = [math.inf] * len(points)
    lengths[source] = 0.0
    queue = [(0.0, source)]
    while queue:
        d, u = heapq.heappop(queue)
        if d != lengths[u]:
            continue
        for v, w in adjacency[u]:
            candidate = d + w
            if candidate < lengths[v]:
                lengths[v] = candidate
                heapq.heappush(queue, (candidate, v))
    return lengths


class JoltLongRangeAttachmentTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.header = PROJECT_H.read_text(encoding="utf-8")
        cls.project = PROJECT_CPP.read_text(encoding="utf-8")
        cls.body = BODY_CPP.read_text(encoding="utf-8")
        cls.jolt_header = JOLT_H.read_text(encoding="utf-8")
        cls.jolt_source = JOLT_CPP.read_text(encoding="utf-8")
        cls.vertex_setup = cls.body.split(
            "JPH::SoftBodySharedSettings::VertexAttributes vertex_attrib;", 1
        )[1].split("settings->Optimize();", 1)[0]

    def test_opt_in_settings_keep_existing_default(self):
        self.assertIn("inline static int soft_body_lra_mode = 0;", self.header)
        self.assertIn("inline static float soft_body_lra_max_distance_multiplier = 1.0f;", self.header)
        self.assertIn(
            '"physics/jolt_physics_3d/simulation/soft_body_lra_mode", PROPERTY_HINT_ENUM, "Disabled,Euclidean,Geodesic"), 0)',
            self.project,
        )
        self.assertIn(
            '"physics/jolt_physics_3d/simulation/soft_body_lra_max_distance_multiplier", PROPERTY_HINT_RANGE, "1,2,0.001,or_greater"), 1.0f)',
            self.project,
        )

    def test_invalid_modes_and_multiplier_are_clamped(self):
        self.assertIn(
            'soft_body_lra_mode = CLAMP((int)GLOBAL_GET("physics/jolt_physics_3d/simulation/soft_body_lra_mode"), 0, 2);',
            self.project,
        )
        self.assertIn("Math::is_finite(lra_multiplier)", self.project)
        self.assertIn("MAX(lra_multiplier, 1.0f) : 1.0f;", self.project)
        for value, expected in ((-3, 0), (0, 0), (1, 1), (2, 2), (10, 2)):
            self.assertEqual(min(max(value, 0), 2), expected)
        for raw in (0.0, 0.2, 1.0, 1.01, 2.0, float('nan'), float('inf')):
            corrected = max(raw, 1.0) if math.isfinite(raw) else 1.0
            self.assertTrue(math.isfinite(corrected))
            self.assertGreaterEqual(corrected, 1.0)

    def test_jolt_lra_uses_pinned_vertices_before_constraints(self):
        setup = self.vertex_setup
        self.assertIn("if (!pinned_vertices.is_empty()) {", setup)
        self.assertIn("using LRAType = JPH::SoftBodySharedSettings::ELRAType;", setup)
        self.assertIn("lra_mode == 1 ? LRAType::EuclideanDistance", setup)
        self.assertIn("lra_mode == 2 ? LRAType::GeodesicDistance : LRAType::None", setup)
        self.assertIn("vertex_attrib.mLRAType", setup)
        self.assertIn("vertex_attrib.mLRAMaxDistanceMultiplier", setup)
        self.assertIn("settings->CreateConstraints(&vertex_attrib, 1, bend_type);", setup)
        self.assertLess(setup.index("vertex_attrib.mLRAType"), setup.index("settings->CreateConstraints"))
        body_setup = self.body.split("JPH::SoftBodySharedSettings *JoltSoftBody3D::_create_shared_settings() {", 1)[1]
        self.assertLess(body_setup.index("pin_vertices(*this, pinned_vertices"),
                        body_setup.index("JPH::SoftBodySharedSettings::VertexAttributes vertex_attrib;"))
        self.assertLess(body_setup.index("settings->CreateConstraints"), body_setup.index("settings->Optimize();"))

    def test_library_uses_closest_kinematic_and_correct_lra_lengths(self):
        self.assertIn("enum class ELRAType", self.jolt_header)
        self.assertIn("EuclideanDistance", self.jolt_header)
        self.assertIn("GeodesicDistance", self.jolt_header)
        self.assertIn("mLRAType = ELRAType::None", self.jolt_header)
        self.assertIn("mLRAMaxDistanceMultiplier = 1.0f", self.jolt_header)
        self.assertIn("CalculateClosestKinematic();", self.jolt_source)
        self.assertIn("case ELRAType::GeodesicDistance:", self.jolt_source)
        self.assertIn("case ELRAType::EuclideanDistance:", self.jolt_source)
        self.assertIn("va.mLRAMaxDistanceMultiplier * mClosestKinematic[v].mDistance", self.jolt_source)

    def test_geodesic_path_bounds_euclidean_on_random_connected_grids(self):
        rng = random.Random(20261119)
        for trial in range(256):
            side = rng.randrange(3, 10)
            pts = [(float(x), float(y), rng.uniform(-0.5, 0.5))
                   for y in range(side) for x in range(side)]
            edges = []
            for y in range(side):
                for x in range(side):
                    i = y * side + x
                    if x + 1 < side:
                        edges.append((i, i + 1))
                    if y + 1 < side:
                        edges.append((i, i + side))
            distances = shortest_path(pts, edges, 0)
            for i in range(len(pts)):
                self.assertGreaterEqual(distances[i] + 1.0e-7, euclidean(pts[0], pts[i]))

    def test_native_script_checks_pins_and_three_modes(self):
        s = SCRIPT.read_text(encoding="utf-8")
        self.assertIn("const SIDE := 12", s)
        self.assertIn("const STEP_COUNT := 90", s)
        self.assertIn("PhysicsServer3D.soft_body_pin_point(body, x, true)", s)
        self.assertIn("PhysicsServer3D.soft_body_set_space(body, space)", s)
        self.assertLess(s.index("soft_body_pin_point(body, x, true)"),
                        s.index("soft_body_set_space(body, space)"))
        self.assertIn("if mode > 0 and anchor_distance", s)
        self.assertIn("JOLT_SOFTBODY_LRA_RESULT:", s)
        self.assertIn("Jolt soft-body LRA regression passed.", s)


if __name__ == "__main__":
    unittest.main()
